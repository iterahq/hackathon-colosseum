// Generates the data migration that copies avatar names and epithets from
// supabase/functions/_shared/tera-lore.json into itera.shop_items.
//
//   node scripts/hackathon/gen-avatar-lore-migration.mjs 0143_avatar_lore.sql
//
// Only rows of kind 'avatar' whose key is in the lore are touched, and only
// title_i18n / description_i18n. Re-run after editing the JSON, then apply.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const lore = JSON.parse(readFileSync(join(root, 'supabase/functions/_shared/tera-lore.json'), 'utf8'));
const out = process.argv[2];
if (!out || !/^\d{4}_[a-z0-9_]+\.sql$/.test(out)) {
  console.error('usage: gen-avatar-lore-migration.mjs <NNNN_name.sql>');
  process.exit(1);
}

const TAG = '$lore$';
function quote(text) {
  if (typeof text !== 'string' || !text.trim()) throw new Error('empty lore text');
  if (text.includes(TAG)) throw new Error(`text contains ${TAG}`);
  return `${TAG}${text}${TAG}`;
}

const rows = Object.entries(lore.avatars).map(([key, entry]) => {
  if (!/^[a-z0-9_]{1,64}$/.test(key)) throw new Error(`bad key ${key}`);
  const { name, epithet } = entry;
  return `  ('${key}', ${quote(name.pt)}, ${quote(name.en)}, ${quote(epithet.pt)}, ${quote(epithet.en)})`;
});

const sql = `-- ============================================================================
-- HACKATHON ONLY (iterahq/hackathon-colosseum, Supabase nyzcbnnbffsizshiolbh).
-- Avatar lore: the names and epithets of the Tera avatars.
-- GENERATED by scripts/hackathon/gen-avatar-lore-migration.mjs from
-- supabase/functions/_shared/tera-lore.json. Do not edit by hand.
-- Touches only itera.shop_items rows of kind 'avatar' listed below, and only
-- title_i18n / description_i18n. Idempotent.
-- ============================================================================

update itera.shop_items as s
set title_i18n = jsonb_build_object('pt', v.name_pt, 'en', v.name_en),
    description_i18n = jsonb_build_object('pt', v.epithet_pt, 'en', v.epithet_en)
from (values
${rows.join(',\n')}
) as v(key, name_pt, name_en, epithet_pt, epithet_en)
where s.key = v.key
  and s.kind = 'avatar';
`;
writeFileSync(join(root, 'db/migrations', out), sql);
console.log(`wrote db/migrations/${out} (${rows.length} lore entries)`);
