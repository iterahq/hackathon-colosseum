// Generates db/migrations/0144_avatars_batch_2.sql: 18 new avatar rows (names and epithets from
// supabase/functions/_shared/tera-lore.json) plus the image_key switch of eight free faces.
//
//   node scripts/hackathon/gen-avatars-batch2-migration.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const lore = JSON.parse(readFileSync(join(root, 'supabase/functions/_shared/tera-lore.json'), 'utf8'));

const TIERS = {
  free: { rarity: 'common', cents: 0, lamports: null, label: 'Free', crystals: null, cap: null, flags: false },
  common: { rarity: 'common', cents: 20, lamports: 1100000, label: 'US$ 0.20 ≈ 0.0011 SOL', crystals: 150, cap: null, flags: true },
  rare: { rarity: 'rare', cents: 100, lamports: 5500000, label: 'US$ 1.00 ≈ 0.0055 SOL', crystals: 600, cap: 500, flags: true },
  epic: { rarity: 'epic', cents: 1000, lamports: 55000000, label: 'US$ 10.00 ≈ 0.055 SOL', crystals: 2500, cap: 100, flags: true },
  legendary: { rarity: 'legendary', cents: 10000, lamports: 550000000, label: 'US$ 100.00 ≈ 0.55 SOL', crystals: 10000, cap: 25, flags: true },
};

// [key, tier, group, sort]
const NEW = [
  ['code_deployando', 'free', 'base', 1091],
  ['code_conquistando', 'free', 'base', 1092],
  ['code_stack_overflow', 'free', 'base', 1093],
  ['code_404', 'free', 'base', 1094],
  ['color_azul', 'common', 'base', 1180],
  ['color_roxo', 'common', 'base', 1185],
  ['color_dourado', 'common', 'base', 1190],
  ['acc_cibernetico', 'common', 'accessory', 1250],
  ['acc_oculos_codificador', 'common', 'accessory', 1260],
  ['acc_capuz_verde', 'common', 'accessory', 1270],
  ['lang_javascript', 'rare', 'special', 1562],
  ['lang_python', 'rare', 'special', 1564],
  ['lang_solidity', 'rare', 'special', 1566],
  ['lang_rust', 'rare', 'special', 1568],
  ['rarity_comum', 'common', 'special', 1570],
  ['rarity_raro', 'rare', 'special', 1572],
  ['rarity_epico', 'epic', 'special', 1574],
  ['rarity_lendario', 'legendary', 'special', 1576],
];

const SWITCH = ['normal', 'feliz', 'determinado', 'piscada', 'surpreso', 'focado', 'triste', 'sorriso'];

const TAG = '$lore$';
function q(text) {
  if (typeof text !== 'string' || !text.trim()) throw new Error('empty text');
  if (text.includes(TAG)) throw new Error('tag in text');
  return `${TAG}${text}${TAG}`;
}
const num = (v) => (v === null ? 'null' : String(v));

const rows = NEW.map(([key, tierName, group, sort]) => {
  if (!/^[a-z0-9_]{1,64}$/.test(key)) throw new Error(`bad key ${key}`);
  const t = TIERS[tierName];
  const l = lore.avatars[key];
  if (!l) throw new Error(`no lore for ${key}`);
  const title = `jsonb_build_object('pt', ${q(l.name.pt)}, 'en', ${q(l.name.en)})`;
  const desc = `jsonb_build_object('pt', ${q(l.epithet.pt)}, 'en', ${q(l.epithet.en)})`;
  return `  ('${key}', 'avatar', ${num(t.lamports)}, ${t.cents}, '${t.label}', ${title}, ${desc}, '{}', true, ${sort}, '{}', ${num(t.crystals)}, '${t.rarity}', '${group}', ${num(t.cap)}, '${key}', ${t.flags}, ${t.flags})`;
});

const updates = SWITCH.map((n) => `update itera.shop_items set image_key = 'tera_a_${n}' where key = 'tera_${n}' and kind = 'avatar';`);

const sql = `-- ============================================================================
-- HACKATHON ONLY (iterahq/hackathon-colosseum, Supabase nyzcbnnbffsizshiolbh).
-- Avatars batch 2: 18 new catalog rows and sharper art for eight free faces.
-- GENERATED by scripts/hackathon/gen-avatars-batch2-migration.mjs from
-- supabase/functions/_shared/tera-lore.json. Idempotent: new rows use
-- on conflict do nothing; the image_key updates are plain and repeatable.
-- Prices follow the live tiers (free 0; common 20c/150; rare 100c/600 cap 500;
-- epic 1000c/2500 cap 100; legendary 10000c/10000 cap 25).
-- ============================================================================

insert into itera.shop_items
  (key, kind, price_lamports, price_usd_cents, price_label, title_i18n, description_i18n, effect, active, sort, art, price_crystals, rarity, avatar_group, supply_cap, image_key, sol_enabled, crystals_enabled)
values
${rows.join(',\n')}
on conflict (key) do nothing;

${updates.join('\n')}
`;
writeFileSync(join(root, 'db/migrations/0144_avatars_batch_2.sql'), sql);
console.log(`wrote db/migrations/0144_avatars_batch_2.sql (${rows.length} rows, ${updates.length} updates)`);
