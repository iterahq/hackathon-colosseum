#!/usr/bin/env bash
# verify-docs.sh — Validate that documentation matches reality.
#
# Usage: ./scripts/verify-docs.sh [DOC ...]
#        default: CLAUDE.md AGENTS.md repo-contract.yaml .claude/manifest.yaml
#
# Guards against doc↔code drift: paths cited in docs that no longer exist, env
# vars documented but never read, API routes that vanished, npm scripts that
# were renamed. Exits non-zero when it finds anything, so it can be a CI gate.
#
# 2026-07-31 — this script existed since the repo's foundation commit but was
# never invoked by any workflow, and it was BROKEN in a way that hid that fact:
#   * `set -e` + a `grep` that legitimately matches nothing (step 2 finds no
#     `FOO=bar` in CLAUDE.md) aborted the whole run at step 2. Steps 3/4/5 never
#     executed once. Every grep is guarded now.
#   * `ERRORS=$((ERRORS+1))` ran inside a `while` on the right-hand side of a
#     pipe — a SUBSHELL — so the counter never reached the parent and the script
#     could only ever exit 0. Findings now go to a temp file the parent reads.
# Two false-positive classes are excluded deliberately (see step 1).
set -euo pipefail

DOCS=("$@")
if [ ${#DOCS[@]} -eq 0 ]; then
  DOCS=(CLAUDE.md AGENTS.md repo-contract.yaml .claude/manifest.yaml db/README.md)
fi

FINDINGS="$(mktemp)"
trap 'rm -f "$FINDINGS"' EXIT

report() { echo "$1"; echo "$1" >>"$FINDINGS"; }

for DOC in "${DOCS[@]}"; do
  if [ ! -f "$DOC" ]; then
    report "FATAL: $DOC not found"
    continue
  fi

  echo "=== Verifying $DOC ==="

  # 1. File path references exist.
  #
  # Two exclusions, both false-positive classes measured on this repo:
  #   (a) QUALIFIED paths — a candidate preceded by `/`, `:`, `@` or a word char
  #       is a fragment of a longer path that is NOT ours. Real examples:
  #       `node_modules/@monaco-editor/loader/lib/es/config/index.js` (the `lib/…`
  #       tail is inside node_modules) and `iterahq/itera-mcp:src/tools/activities.ts`
  #       (another repo, correctly written with a `repo:` prefix). Cross-repo
  #       references MUST carry a `<repo>:` or `<org>/<repo>:` prefix to be
  #       recognised as such — write them that way.
  #   (b) GITIGNORED paths — build output, not drift. `public/vendor/monaco/vs`
  #       is generated by `scripts/vendor-monaco.ts` at build time and is
  #       gitignored on purpose; asserting it exists in a fresh checkout would
  #       be wrong.
  #
  # Plus a line-level opt-out: a line carrying the marker `verify-docs:allow-missing`
  # is skipped entirely. It exists for HISTORICAL PROSE — a doc that names a path
  # precisely because it was DELETED ("o engine legado vivia em src/pages/LessonPage.tsx")
  # is correct documentation, and the checker cannot tell that from a stale
  # pointer. Use it only with such a sentence right there; never to silence a
  # live reference.
  echo "--- File path references ---"
  { grep -vF 'verify-docs:allow-missing' "$DOC" \
      | grep -oE '(^|[^A-Za-z0-9_/:.@-])(src|lib|app|packages|scripts|config|public|db)/[A-Za-z0-9_./-]+' || true; } \
    | sed -E 's/^[^A-Za-z]+//; s/[.,;:)]+$//' \
    | sort -u \
    | while read -r p; do
        [ -n "$p" ] || continue
        [ -e "$p" ] && continue
        if git check-ignore -q "$p" 2>/dev/null; then
          echo "  (skip, build output / gitignored: $p)"
          continue
        fi
        report "MISSING PATH: $p  [$DOC]"
      done

  # 2. Env vars documented as `NAME=value` are actually read in source.
  echo "--- Environment variables ---"
  { grep -oE '[A-Z][A-Z0-9_]{2,}=[^ ]*' "$DOC" || true; } | cut -d= -f1 | sort -u | while read -r var; do
    [ -n "$var" ] || continue
    if ! grep -rq "$var" src/ lib/ app/ db/ scripts/ e2e/ 2>/dev/null; then
      report "UNUSED ENV: $var (documented but not found in source)  [$DOC]"
    fi
  done

  # 3. Documented API routes exist in code.
  echo "--- API routes ---"
  { grep -oE '(GET|POST|PUT|PATCH|DELETE) /api/[^ )`]*' "$DOC" || true; } | while read -r method route; do
    [ -n "${route:-}" ] || continue
    if ! grep -rq "${route}" src/ app/ pages/ 2>/dev/null; then
      report "MISSING ROUTE: $method $route  [$DOC]"
    fi
  done

  # 4. Setup commands reference tools that exist.
  echo "--- Setup commands ---"
  { grep -E '^[[:space:]]*(npm|pnpm|yarn|bun|npx|make|cargo|pip) ' "$DOC" || true; } | head -5 | while read -r cmd; do
    tool=$(echo "$cmd" | awk '{print $1}')
    [ -n "$tool" ] || continue
    if ! command -v "$tool" >/dev/null 2>&1; then
      report "TOOL NOT FOUND: $tool (used in setup commands)  [$DOC]"
    fi
  done

  # 5. npm scripts referenced in docs exist in package.json.
  # Uses node, not jq: node is guaranteed present wherever this repo builds.
  echo "--- Package scripts ---"
  if [ -f package.json ]; then
    { grep -oE 'npm run [a-z][a-z0-9:_-]*' "$DOC" || true; } | sed 's/npm run //' | sort -u | while read -r script; do
      [ -n "$script" ] || continue
      if ! node -e 'const s=require("./package.json").scripts||{};process.exit(s[process.argv[1]]?0:1)' "$script"; then
        report "MISSING SCRIPT: npm run $script  [$DOC]"
      fi
    done
  fi
done

echo
if [ -s "$FINDINGS" ]; then
  echo "=== FAILED — $(wc -l <"$FINDINGS") finding(s) ==="
  echo "Docs disagree with the code. Fix the doc, or fix the code, or (for a"
  echo "cross-repo path) write it qualified as '<repo>:path/to/file'."
  exit 1
fi
echo "=== Done — docs match the code ==="
