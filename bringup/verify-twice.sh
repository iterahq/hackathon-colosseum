#!/usr/bin/env bash
# =============================================================================
# verify-twice.sh — the claim of this whole directory, mechanised.
#
# WHAT IT PROVES THAT THE TEST SUITE DOES NOT
# -------------------------------------------
# `e2e/bringup-capture.spec.ts` captures each screen twice IN ONE RUN, against
# ONE database. That catches wall clocks, unseeded randomness and late fonts.
#
# It cannot catch the failure that matters most to a scheduled capture: a
# screenshot that depends on something the DATABASE generated. Every teardown
# gives new `auth.users` ids, new tenant uuids from `gen_random_uuid()`, and new
# `created_at` timestamps. If any of those reaches a pixel — an id in a URL bar,
# a "member since" line, a colour derived from a uuid — the images differ
# between two runs of the pipeline while every in-run assertion stays green.
#
# So this script destroys the stack, builds it again from zero, captures again,
# and compares the two sets of bytes. That is the question the version history
# actually asks: "is this capture different because the PRODUCT changed?"
#
# ⚠️ ONE HOST. Glyph rasterisation belongs to the host's FreeType/fontconfig,
# so this proves reproducibility ON THIS MACHINE. A cross-machine comparison
# must run in one container, and nothing here promises otherwise.
#
# USAGE
#   bringup/verify-twice.sh
#
# EXIT
#   0  every screen identical across two full rebuilds
#   1  at least one screen differed — the report names which
#   2  a bring-up or a capture failed before any comparison was possible
# =============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${HERE}/.." && pwd)"

# shellcheck source=bringup/env.sh
. "${HERE}/env.sh"

ART="${ROOT}/e2e/artifacts/bringup"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

say() { printf '[verify-twice] %s\n' "$*" >&2; }

# `screenshot.png` AND `regions.json`. An identical image with a drifting map
# means one click resolves to two different files on two runs — a worse failure
# than a wobbling pixel, and invisible to an image-only comparison.
snapshot_hashes() {
  local dest="$1"
  : > "$dest"
  for dir in "${ART}"/*/; do
    [[ -f "${dir}screenshot.png" ]] || continue
    printf '%s png %s\n'  "$(basename "$dir")" "$(sha256sum "${dir}screenshot.png" | awk '{print $1}')" >> "$dest"
    printf '%s json %s\n' "$(basename "$dir")" "$(sha256sum "${dir}regions.json"  | awk '{print $1}')" >> "$dest"
  done
  sort -o "$dest" "$dest"
}

one_pass() {
  local label="$1" dest="$2"
  say "── ${label}: destroying any existing stack ──"
  bash "${HERE}/down.sh" >/dev/null 2>&1

  say "── ${label}: standing the stack up from zero ──"
  bash "${HERE}/up.sh" >/dev/null || return 2

  say "── ${label}: capturing ──"
  rm -rf "${ART}"
  ( cd "${ROOT}" && CI=1 npm run e2e:bringup ) >/dev/null 2>&1 || return 2

  snapshot_hashes "$dest"
  [[ -s "$dest" ]] || return 2
}

one_pass "pass 1" "${WORK}/a.txt" || { say "pass 1 failed"; exit 2; }
one_pass "pass 2" "${WORK}/b.txt" || { say "pass 2 failed"; exit 2; }

say ""
say "screen/artifact          pass 1            pass 2            same"
rc=0
while read -r screen kind hash_a; do
  hash_b=$(awk -v s="$screen" -v k="$kind" '$1==s && $2==k {print $3}' "${WORK}/b.txt")
  if [[ "$hash_a" == "$hash_b" ]]; then
    verdict="yes"
  else
    verdict="NO"
    rc=1
  fi
  printf '[verify-twice] %-24s %-17s %-17s %s\n' \
    "${screen}/${kind}" "${hash_a:0:16}" "${hash_b:0:16}" "$verdict" >&2
done < "${WORK}/a.txt"

say ""
if [[ "$rc" -eq 0 ]]; then
  say "IDENTICAL across two full rebuilds. Nothing the database generates —"
  say "auth uids, tenant uuids, created_at — reaches a pixel or a region box."
else
  say "DIFFERED. Something generated by the database reaches the output. Until"
  say "that is found, a version diff cannot distinguish 'the product changed'"
  say "from 'the stack was rebuilt'."
fi
exit "$rc"
