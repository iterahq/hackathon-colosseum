export const DEFAULT_LOCALE: Locale = 'pt';

/** The locale a browser asks for: Portuguese for any pt-* language, English for everything else; `null` with no signal. */
export function localeFromLanguages(languages: readonly string[] | undefined): Locale | null {
  const first = languages?.find((l) => typeof l === 'string' && l.trim() !== '');
  if (!first) return null;
  return first.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

/**
 * The startup locale. An explicit, persisted choice (localStorage) wins; a first visit follows the browser's
 * language (`navigator.languages`), so an en-US visitor reads English and a pt-BR one Portuguese; with no
 * signal at all the canonical app language is pt-BR. The DB-backed per-user preference (itera.users.locale)
 * is applied on top of this once the profile loads (see useLocaleSync).
 */
function detectLocale(): Locale {
  const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('itera.locale') : null;
  if (stored === 'pt' || stored === 'en') return stored;
  if (typeof navigator !== 'undefined') {
    const fromBrowser = localeFromLanguages(navigator.languages?.length ? navigator.languages : [navigator.language]);
    if (fromBrowser) return fromBrowser;
  }
  return DEFAULT_LOCALE;
}

interface I18nState {
  locale: Locale;
  /**
   * Set the active locale. By default (`persist=true`) the change is written to
   * localStorage AND propagated to the registered persist sink (the DB writer
   * wired by useLocaleSync). Pass `persist=false` to HYDRATE from an external
   * source of truth (the user's stored profile locale) without echoing it back.
   */
  setLocale: (l: Locale, persist?: boolean) => void;
  toggleLocale: () => void;
  /** Register a sink that persists a user-initiated locale change (e.g. to the DB). */
  registerPersistSink: (fn: ((l: Locale) => void) | null) => void;
  /**
   * Interpolation values accept numbers as well as strings: callers routinely
   * pass counts (`{ answered, total }`), and the implementation stringifies
   * them before substitution.
   */
  t: (key: string, vars?: Record<string, string | number>) => string;
  /** Resolve a bilingual jsonb bag ({ pt, en }) for the current locale. */
  tText: (bag: Record<string, string | undefined> | null | undefined) => string;
}

const I18nCtx = createContext<I18nState | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);
  // A mutable sink (registered by useLocaleSync) that persists user-initiated
  // locale changes to the DB. Kept in a ref so changing it doesn't re-render.
  const persistRef = useRef<((l: Locale) => void) | null>(null);

  useEffect(() => {
    if (typeof document !== 'undefined') document.documentElement.lang = locale === 'pt' ? 'pt-BR' : 'en';
    // The readers outside React (`resolveLocalizedSpec`, the boot script) take the locale from storage: a first visit
    // that followed the browser language writes it there once, so the content and the chrome speak the same language.
    if (typeof localStorage !== 'undefined' && localStorage.getItem('itera.locale') === null) localStorage.setItem('itera.locale', locale);
  }, [locale]);

  const value = useMemo<I18nState>(() => {
    const setLocale = (l: Locale, persist = true) => {
      setLocaleState(l);
      if (typeof localStorage !== 'undefined') localStorage.setItem('itera.locale', l);
      if (persist && persistRef.current) persistRef.current(l);
    };
    return {
      locale,
      setLocale,
      toggleLocale: () => setLocale(locale === 'pt' ? 'en' : 'pt'),
      registerPersistSink: (fn) => {
        persistRef.current = fn;
      },
      t: (key, vars) => {
        let str = resources[locale][key] ?? resources.en[key] ?? key;
        if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
        return str;
      },
      tText: (bag) => {
        if (!bag) return '';
        return bag[locale] ?? bag.en ?? bag.pt ?? Object.values(bag).find(Boolean) ?? '';
      },
    };
  }, [locale]);

  return createElement(I18nCtx.Provider, { value }, children);
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error('useI18n must be used within <I18nProvider>');
  return ctx;
}
