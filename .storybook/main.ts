import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import type { StorybookConfig } from '@storybook/react-vite';
import type { Alias, AliasOptions } from 'vite';
import { createPlaygroundIndexer } from '../scripts/storybook-playground-indexer';

const asArray = (alias: AliasOptions | undefined): Alias[] =>
  Array.isArray(alias)
    ? alias
    : Object.entries(alias ?? {}).map(([find, replacement]) => ({ find, replacement }));

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const config: StorybookConfig = {
  stories: [
    '../src/**/*.stories.@(ts|tsx)',
    // Designer brainstorm space — see "Story/Component ownership" in CLAUDE.md/AGENTS.md.
    '../design-playground/**/*.stories.@(ts|tsx)',
    // "🆕 PR #N" re-exports inside Design Playground — generated by
    // `scripts/generate-nesta-pr-stories.ts` before `build-storybook`, PR
    // builds only. Gitignored; absent on a `main` build
    // (`deploy-storybook.yml` never runs the generator), so this glob simply
    // matches nothing there.
    '../.storybook/generated/**/*.stories.@(ts|tsx)',
  ],
  addons: ['@storybook/addon-docs'],
  /**
   * Stamps every Design Playground story (real ones under
   * `design-playground/`, and PR re-exports under `.storybook/generated/`)
   * with a `playground-order:<score>` tag, read back by `preview.tsx`'s
   * `storySort` to sort the group "send order, most recent first". See
   * `scripts/storybook-playground-indexer.ts` and
   * `scripts/storybook-playground-order.ts` for why this has to happen here
   * (full Node/git access) rather than inside `storySort` itself (which runs
   * isolated, no imports).
   */
  experimental_indexers: (existingIndexers) => [
    createPlaygroundIndexer(REPO_ROOT),
    ...(existingIndexers ?? []),
  ],
  /**
   * Serve `public/` (React UMD + Tailwind Play do preview do snack, e o Monaco
   * vendorizado em `public/vendor/monaco/vs`). O builder Vite do Storybook não
   * herda o `publicDir` da config do app, então precisa ser explícito — sem
   * isso o editor de código das stories cairia em 404 ao buscar o loader.
   */
  staticDirs: ['../public'],
  framework: {
    name: '@storybook/react-vite',
    options: {},
  },
  /**
   * Reuse the app's vite.config (the `@` alias, swapy shim, define vars), mais o
   * ÚNICO desvio da vitrine: a itera-api falsa (`.storybook/mocks/iteraApi.ts`).
   * O `find` é ancorado de propósito — `@/api/iteraApiError` é outro módulo, e
   * casamento por prefixo o arrastaria junto.
   */
  viteFinal: async (cfg) => ({
    ...cfg,
    resolve: {
      ...cfg.resolve,
      alias: [
        {
          find: /^@\/api\/iteraApi$/,
          replacement: fileURLToPath(new URL('./mocks/iteraApi.ts', import.meta.url)),
        },
        ...asArray(cfg.resolve?.alias),
      ],
    },
  }),
};

export default config;
